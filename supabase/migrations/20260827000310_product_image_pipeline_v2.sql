-- Helpers para RLS de Storage. La ruta V2 es:
-- <organizacion_uuid>/productos/<producto_uuid>/(full|thumb).webp
CREATE OR REPLACE FUNCTION noven_private.puede_insertar_imagen_catalogo_storage(p_name text)
RETURNS boolean
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_org uuid;
  v_producto uuid;
  v_archivo text;
BEGIN
  IF (SELECT auth.uid()) IS NULL THEN RETURN false; END IF;
  IF pg_catalog.split_part(p_name, '/', 2) <> 'productos' THEN RETURN false; END IF;
  v_archivo := pg_catalog.split_part(p_name, '/', 4);
  IF v_archivo NOT IN ('full.webp', 'thumb.webp') THEN RETURN false; END IF;

  BEGIN
    v_org := pg_catalog.split_part(p_name, '/', 1)::uuid;
    v_producto := pg_catalog.split_part(p_name, '/', 3)::uuid;
  EXCEPTION WHEN invalid_text_representation THEN
    RETURN false;
  END;

  RETURN EXISTS (
    SELECT 1
    FROM public.productos p
    JOIN public.producto_sucursal ps
      ON ps.producto_id = p.id
     AND ps.organizacion_id = p.organizacion_id
    WHERE p.id = v_producto
      AND p.organizacion_id = v_org
      AND noven_private.puede_ver_producto_sucursal(ps.sucursal_id, p.id)
  );
END;
$$;

REVOKE ALL ON FUNCTION noven_private.puede_insertar_imagen_catalogo_storage(text)
  FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION noven_private.puede_insertar_imagen_catalogo_storage(text)
  TO authenticated;

CREATE OR REPLACE FUNCTION noven_private.puede_actualizar_imagen_catalogo_storage(p_name text)
RETURNS boolean
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_org uuid;
  v_producto uuid;
  v_archivo text;
  v_imagen_actual text;
BEGIN
  IF NOT noven_private.puede_insertar_imagen_catalogo_storage(p_name) THEN RETURN false; END IF;

  v_archivo := pg_catalog.split_part(p_name, '/', 4);
  BEGIN
    v_org := pg_catalog.split_part(p_name, '/', 1)::uuid;
    v_producto := pg_catalog.split_part(p_name, '/', 3)::uuid;
  EXCEPTION WHEN invalid_text_representation THEN
    RETURN false;
  END;

  SELECT p.imagen_url
  INTO v_imagen_actual
  FROM public.productos p
  WHERE p.id = v_producto
    AND p.organizacion_id = v_org;

  -- Permite reintentar una primera carga que dejó el objeto creado pero aún no
  -- actualizó el catálogo. Una vez que hay foto oficial, sólo roles elevados.
  IF NULLIF(btrim(COALESCE(v_imagen_actual, '')), '') IS NULL THEN RETURN true; END IF;

  RETURN EXISTS (
    SELECT 1
    FROM public.usuario_accesos ua
    WHERE ua.usuario_id = (SELECT auth.uid())
      AND ua.organizacion_id = v_org
      AND ua.activo = true
      AND ua.rol IN ('admin_organizacion', 'gerente_zonal', 'gerente_sucursal', 'supervisor')
  );
END;
$$;

REVOKE ALL ON FUNCTION noven_private.puede_actualizar_imagen_catalogo_storage(text)
  FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION noven_private.puede_actualizar_imagen_catalogo_storage(text)
  TO authenticated;

COMMIT;
