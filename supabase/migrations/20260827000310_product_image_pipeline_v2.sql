-- =============================================================================
-- NOVEN · PRODUCT IMAGE PIPELINE V2
--
-- Objetivo:
--   - una foto de catálogo por producto global, compartida por la organización;
--   - thumbnail separado para listas móviles;
--   - auditoría de alta/reemplazo;
--   - operadores pueden agregar una foto faltante;
--   - reemplazos requieren supervisor/gerencia;
--   - compatibilidad con URLs legacy hasta que cada SKU sea actualizado.
--
-- Esta migración es ADITIVA. El hardening del bucket se hace en 00320 una vez
-- que el frontend V2 esté desplegado.
-- =============================================================================

BEGIN;

ALTER TABLE public.productos
  ADD COLUMN IF NOT EXISTS imagen_thumb_url text;

GRANT SELECT (imagen_thumb_url) ON TABLE public.productos TO authenticated;

CREATE TABLE IF NOT EXISTS public.producto_imagen_cambios (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organizacion_id uuid NOT NULL REFERENCES public.organizaciones(id) ON DELETE CASCADE,
  producto_id uuid NOT NULL,
  sucursal_id uuid NOT NULL,
  usuario_id uuid NOT NULL REFERENCES public.usuarios(id) ON DELETE RESTRICT,
  accion text NOT NULL CHECK (accion IN ('agregar', 'reemplazar')),
  imagen_url text NOT NULL,
  imagen_thumb_url text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT producto_imagen_cambios_producto_org_fk
    FOREIGN KEY (producto_id, organizacion_id)
    REFERENCES public.productos(id, organizacion_id)
    ON DELETE CASCADE,
  CONSTRAINT producto_imagen_cambios_sucursal_org_fk
    FOREIGN KEY (sucursal_id, organizacion_id)
    REFERENCES public.sucursales(id, organizacion_id)
    ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS producto_imagen_cambios_producto_fecha_idx
  ON public.producto_imagen_cambios(producto_id, created_at DESC);

CREATE INDEX IF NOT EXISTS producto_imagen_cambios_sucursal_fecha_idx
  ON public.producto_imagen_cambios(sucursal_id, created_at DESC);

ALTER TABLE public.producto_imagen_cambios ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.producto_imagen_cambios FROM PUBLIC, anon, authenticated;

DROP VIEW IF EXISTS public.v_vencimientos_operativos;

CREATE VIEW public.v_vencimientos_operativos
WITH (security_invoker = true)
AS
SELECT
  v.id,
  v.producto_id,
  v.sucursal_id,
  v.usuario_id,
  v.cantidad,
  v.lote,
  v.fecha_vencimiento,
  v.fecha_carga,
  v.activo,
  v.created_at,
  v.updated_at,
  v.nivel_actual,

  p.organizacion_id,
  p.cod_art,
  p.codigo_barras,
  p.descripcion,
  p.marca,
  p.gramaje,
  p.categoria,
  p.proveedor,
  p.sector,
  p.precio_costo,
  p.imagen_url,
  p.imagen_thumb_url,
  p.familia_id,
  p.activo AS producto_activo,
  p.created_at AS producto_created_at,
  p.updated_at AS producto_updated_at,

  f.sector_id,
  s.nombre AS sector_nombre,
  s.dias_donacion,

  ps.stock_actual,
  ps.venta_media_diaria,
  ps.fecha_ultima_importacion,
  ps.updated_at AS estado_updated_at
FROM public.vencimientos v
JOIN public.productos p
  ON p.id = v.producto_id
JOIN public.producto_sucursal ps
  ON ps.producto_id = v.producto_id
 AND ps.sucursal_id = v.sucursal_id
 AND ps.organizacion_id = p.organizacion_id
LEFT JOIN public.familias f
  ON f.id = p.familia_id
 AND f.organizacion_id = p.organizacion_id
LEFT JOIN public.sectores s
  ON s.id = f.sector_id
 AND s.organizacion_id = p.organizacion_id;

REVOKE ALL ON TABLE public.v_vencimientos_operativos FROM PUBLIC, anon;
GRANT SELECT ON TABLE public.v_vencimientos_operativos TO authenticated;

