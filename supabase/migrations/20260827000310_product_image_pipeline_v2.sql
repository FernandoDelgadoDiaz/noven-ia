  'Vencimientos + catálogo compartido + thumbnails + estado por sucursal + política de donación.';

CREATE OR REPLACE FUNCTION noven_private.puede_reemplazar_imagen_producto(
  p_sucursal_id uuid,
  p_producto_id uuid
)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.productos p
    JOIN public.sucursales s
      ON s.id = p_sucursal_id
     AND s.organizacion_id = p.organizacion_id
     AND s.activa = true
    JOIN public.usuario_accesos ua
      ON ua.usuario_id = (SELECT auth.uid())
     AND ua.organizacion_id = p.organizacion_id
     AND ua.activo = true
    WHERE p.id = p_producto_id
      AND (
        ua.rol = 'admin_organizacion'
        OR (ua.rol = 'gerente_zonal' AND ua.zona_id = s.zona_id)
        OR (ua.rol IN ('gerente_sucursal', 'supervisor') AND ua.sucursal_id = s.id)
      )
  );
$$;

REVOKE ALL ON FUNCTION noven_private.puede_reemplazar_imagen_producto(uuid, uuid)
  FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION noven_private.puede_reemplazar_imagen_producto(uuid, uuid)
  TO authenticated;

CREATE OR REPLACE FUNCTION public.modo_imagen_producto_operador(
  p_sucursal_id uuid,
  p_producto_id uuid
)
RETURNS text
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public, noven_private, pg_temp
AS $$
DECLARE
  v_imagen text;
BEGIN
  IF (SELECT auth.uid()) IS NULL THEN
    RAISE EXCEPTION 'No autenticado' USING ERRCODE = '28000';
  END IF;

  IF NOT noven_private.puede_ver_producto_sucursal(p_sucursal_id, p_producto_id) THEN
    RETURN 'solo_lectura';
  END IF;

  SELECT p.imagen_url
  INTO v_imagen
  FROM public.productos p
  WHERE p.id = p_producto_id;

  IF NOT FOUND THEN
    RETURN 'solo_lectura';
  END IF;

  IF NULLIF(btrim(COALESCE(v_imagen, '')), '') IS NULL THEN
    RETURN 'agregar';
  END IF;

  IF noven_private.puede_reemplazar_imagen_producto(p_sucursal_id, p_producto_id) THEN
    RETURN 'reemplazar';
  END IF;

  RETURN 'solo_lectura';
END;
$$;

REVOKE ALL ON FUNCTION public.modo_imagen_producto_operador(uuid, uuid)
  FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.modo_imagen_producto_operador(uuid, uuid)
  TO authenticated;

CREATE OR REPLACE FUNCTION noven_private.actualizar_imagen_producto_operador_v2_impl(
  p_sucursal_id uuid,
  p_producto_id uuid,
  p_imagen_url text,
  p_imagen_thumb_url text
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_uid uuid := (SELECT auth.uid());
  v_org uuid;
  v_imagen_actual text;
  v_accion text;
  v_fragmento text;
BEGIN
  IF v_uid IS NULL THEN
    RAISE EXCEPTION 'No autenticado' USING ERRCODE = '28000';
  END IF;

  IF NULLIF(btrim(COALESCE(p_imagen_url, '')), '') IS NULL
     OR NULLIF(btrim(COALESCE(p_imagen_thumb_url, '')), '') IS NULL THEN
    RAISE EXCEPTION 'Las URLs de imagen son obligatorias' USING ERRCODE = '22023';
  END IF;

  SELECT p.organizacion_id, p.imagen_url
  INTO v_org, v_imagen_actual
  FROM public.productos p
  JOIN public.sucursales s
    ON s.id = p_sucursal_id
   AND s.organizacion_id = p.organizacion_id
   AND s.activa = true
  WHERE p.id = p_producto_id
  FOR UPDATE OF p;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Producto/sucursal incompatibles o inexistentes' USING ERRCODE = 'P0002';
  END IF;

  IF NOT noven_private.puede_ver_producto_sucursal(p_sucursal_id, p_producto_id) THEN
    RAISE EXCEPTION 'Sin permiso para gestionar la foto de este producto' USING ERRCODE = '42501';
  END IF;

  v_accion := CASE
    WHEN NULLIF(btrim(COALESCE(v_imagen_actual, '')), '') IS NULL THEN 'agregar'
    ELSE 'reemplazar'
  END;

  IF v_accion = 'reemplazar'
     AND NOT noven_private.puede_reemplazar_imagen_producto(p_sucursal_id, p_producto_id) THEN
    RAISE EXCEPTION 'La foto ya existe; el reemplazo requiere supervisor o gerencia' USING ERRCODE = '42501';
  END IF;

  v_fragmento := '/productos-imagenes/' || v_org::text || '/productos/' || p_producto_id::text || '/';
  IF position(v_fragmento IN p_imagen_url) = 0
     OR position(v_fragmento IN p_imagen_thumb_url) = 0
     OR position('/full.webp' IN p_imagen_url) = 0
     OR position('/thumb.webp' IN p_imagen_thumb_url) = 0 THEN
    RAISE EXCEPTION 'Ruta de imagen fuera del catálogo de la organización' USING ERRCODE = '22023';
  END IF;

  UPDATE public.productos
  SET imagen_url = btrim(p_imagen_url),
      imagen_thumb_url = btrim(p_imagen_thumb_url),
      updated_at = pg_catalog.now()
  WHERE id = p_producto_id
    AND organizacion_id = v_org;

  INSERT INTO public.producto_imagen_cambios(
    organizacion_id,
    producto_id,
    sucursal_id,
    usuario_id,
    accion,
    imagen_url,
    imagen_thumb_url
  ) VALUES (
    v_org,
    p_producto_id,
    p_sucursal_id,
    v_uid,
    v_accion,
    btrim(p_imagen_url),
    btrim(p_imagen_thumb_url)
  );
END;
$$;

REVOKE ALL ON FUNCTION noven_private.actualizar_imagen_producto_operador_v2_impl(uuid, uuid, text, text)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION noven_private.actualizar_imagen_producto_operador_v2_impl(uuid, uuid, text, text)
  TO authenticated;

CREATE OR REPLACE FUNCTION public.actualizar_imagen_producto_operador_v2(
